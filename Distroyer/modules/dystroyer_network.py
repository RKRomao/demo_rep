class DystroyerNetworkModule(BaseModule):
    """
    Dystroyer Network - Hybrid Network Defense & Egress Security Analyzer.
    Combines passive inspection with benign, controlled active probes.
    """

    def run(self) -> dict:
        host = self.get_domain()
        mode = self.config.get('net_mode', 'hybrid').lower()  # passive, active, or hybrid

        results = {
            'target_host': host,
            'mode': mode,
            'egress_filtering': {},
            'tls_inspection': {},
            'dns_defense': {},
            'waf_ids_defense': {}
        }

        # -------------------------------------------------------------
        # 1. TLS Inspection & Transparent Proxy Detection (Passive)
        # -------------------------------------------------------------
        results['tls_inspection'] = self._audit_tls_inspection(host)

        # -------------------------------------------------------------
        # 2. DNS Filtering & Sinkholing (Hybrid)
        # -------------------------------------------------------------
        results['dns_defense'] = self._audit_dns_defense(host, active=(mode in ['active', 'hybrid']))

        # -------------------------------------------------------------
        # 3. Egress Filtering L4 (Active / Hybrid)
        # -------------------------------------------------------------
        if mode in ['active', 'hybrid']:
            results['egress_filtering'] = self._audit_egress_filtering()
        else:
            results['egress_filtering'] = {'skipped': 'Passive mode enabled. Egress probes skipped.'}

        # -------------------------------------------------------------
        # 4. WAF & Active IDS/IPS Fingerprinting (Hybrid)
        # -------------------------------------------------------------
        results['waf_ids_defense'] = self._audit_waf_and_ids(active=(mode in ['active', 'hybrid']))

        return self.result(results)

    # =========================================================================
    # 1. TLS & Proxy Inspection Engine
    # =========================================================================
    def _audit_tls_inspection(self, host: str) -> dict:
        tls_data = {
            'intercepted': False,
            'intercept_evidence': None,
            'root_ca': None,
            'proxy_headers_detected': []
        }

        # 1.1 Analyze X.509 Certificate Chain
        try:
            ctx = ssl.create_default_context()
            ctx.check_hostname = False
            ctx.verify_mode = ssl.CERT_NONE  # Get remote raw cert even if untrusted

            with socket.create_connection((host, 443), timeout=min(self.timeout, 5)) as sock:
                with ctx.wrap_socket(sock, server_hostname=host) as ssock:
                    cert = ssock.getpeercert(binary_form=False)
                    # If empty due to CERT_NONE, inspect peer certificate DER
                    der_cert = ssock.getpeercert(binary_form=True)
                    cert_text = str(der_cert)

                    # Look for known inspection appliance signatures
                    for vendor, desc in INSPECTION_CA_SIGNATURES:
                        if vendor.lower().encode() in der_cert.lower() or (cert and vendor.lower() in str(cert).lower()):
                            tls_data['intercepted'] = True
                            tls_data['intercept_evidence'] = desc
                            self.add_finding(
                                title=f"TLS/SSL Deep Packet Inspection Detected ({vendor})",
                                severity="HIGH",
                                detail=f"Outbound HTTPS traffic is decrypted and inspected by {desc}.",
                                evidence=f"Appliance signature matched in TLS Certificate Issuer: {vendor}",
                                recommendation="Be aware that encrypted data and authentication credentials are being decrypted in flight."
                            )
                            break

                    if cert and 'issuer' in cert:
                        issuer_dict = dict(x[0] for x in cert['issuer'])
                        tls_data['root_ca'] = issuer_dict.get('organizationName') or issuer_dict.get('commonName')

        except Exception as e:
            tls_data['tls_handshake_error'] = str(e)

        # 1.2 Inspect Proxy Header Indicators
        try:
            resp = self.get(self.get_base_url(), timeout=min(self.timeout, 5))
            if resp is not None:
                proxy_headers = ['via', 'x-forwarded-for', 'x-forwarded-proto', 'proxy-connection', 'x-cache', 'forwarded']
                found_headers = {}
                for h in proxy_headers:
                    if h in resp.headers:
                        found_headers[h] = resp.headers[h]

                if found_headers:
                    tls_data['proxy_headers_detected'] = found_headers
                    self.add_finding(
                        title="Transparent or Forwarding Web Proxy Detected",
                        severity="INFO",
                        detail="HTTP intermediate headers discovered in response, indicating one or more network proxies in the path.",
                        evidence=str(found_headers),
                        recommendation="Review proxy routing policies and ensure header confidentiality."
                    )
        except Exception:
            pass

        return tls_data

    # =========================================================================
    # 2. DNS Defense & Sinkhole Engine
    # =========================================================================
    def _audit_dns_defense(self, host: str, active: bool = True) -> dict:
        dns_data = {
            'system_resolved_ips': [],
            'external_dns_allowed': None,
            'sinkhole_detected': False,
            'sinkhole_detail': None
        }

        # 2.1 System DNS Resolution
        try:
            resolved = socket.gethostbyname_ex(host)
            dns_data['system_resolved_ips'] = resolved[2]
            
            # Check for common sinkhole IPs (RFC1918 or Loopback / Zero)
            for ip in resolved[2]:
                if ip.startswith(('0.0.0.0', '127.', '10.', '192.168.', '172.16.', '172.17.', '172.18.', '172.19.', '172.20.', '172.31.')):
                    dns_data['sinkhole_detected'] = True
                    dns_data['sinkhole_detail'] = f"Local DNS resolver mapped external domain {host} to private/sinkhole IP: {ip}"
                    self.add_finding(
                        title="DNS Sinkholing / Redirection Detected",
                        severity="MEDIUM",
                        detail=f"Domain {host} resolves to internal or sinkhole IP address {ip}.",
                        evidence=f"Resolved IPs: {resolved[2]}",
                        recommendation="Verify whether DNS sinkholing is configured intentionally for threat isolation."
                    )
                    break
        except Exception as e:
            dns_data['system_dns_error'] = str(e)

        # 2.2 Direct External DNS Egress Test (Port 53 UDP)
        if active:
            dns_servers = ['1.1.1.1', '8.8.8.8']
            direct_query_success = False

            for srv in dns_servers:
                try:
                    # Craft minimal raw DNS query for target host or google.com
                    sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
                    sock.settimeout(2.0)
                    
                    # Transaction ID: 0x1337, Flags: Standard query (0x0100), QDCOUNT: 1
                    query = bytearray()
                    query.extend(b'\x13\x37\x01\x00\x00\x01\x00\x00\x00\x00\x00\x00')
                    for part in "google.com".split('.'):
                        query.append(len(part))
                        query.extend(part.encode('latin1'))
                    query.extend(b'\x00\x00\x01\x00\x01')  # QTYPE: A (1), QCLASS: IN (1)

                    sock.sendto(query, (srv, 53))
                    data, _ = sock.recvfrom(512)
                    sock.close()

                    if len(data) >= 12:
                        direct_query_success = True
                        break
                except socket.timeout:
                    continue
                except Exception:
                    continue

            dns_data['external_dns_allowed'] = direct_query_success
            if not direct_query_success:
                self.add_finding(
                    title="Outbound DNS (Port 53 UDP) Filtered",
                    severity="INFO",
                    detail="Direct DNS queries to external public resolvers (1.1.1.1, 8.8.8.8) are blocked by perimeter firewall.",
                    evidence="Timeout received on raw UDP/53 test queries.",
                    recommendation="Good security posture: enforces local centralized DNS logging and prevents DNS exfiltration."
                )
            else:
                self.add_finding(
                    title="Unrestricted Outbound DNS Egress (UDP 53 Allowed)",
                    severity="LOW",
                    detail="Internal hosts can query external public DNS resolvers directly on UDP port 53.",
                    evidence="Received valid DNS response directly from public resolver.",
                    recommendation="Consider restricting port 53 UDP outbound to authorized internal DNS servers to prevent DNS tunneling."
                )

        return dns_data

    # =========================================================================
    # 3. Egress Filtering L4 Engine (Outbound Reachability)
    # =========================================================================
    def _audit_egress_filtering(self) -> dict:
        egress_data = {'ports_tested': len(EGRESS_PORTS), 'results': {}}
        
        # Test targets for public egress verification
        # We test outbound connectivity to reliable high-availability public targets
        probe_target = "1.1.1.1"

        def _test_port(port, info):
            proto, desc = info
            sock = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
            sock.settimeout(2.0)
            start_t = time.time()
            try:
                res = sock.connect_ex((probe_target, port))
                elapsed = round((time.time() - start_t) * 1000, 1)
                sock.close()
                if res == 0:
                    return port, {'status': 'OPEN', 'response_ms': elapsed, 'proto': proto, 'desc': desc}
                elif res in (10061, 111):  # ECONNREFUSED (RST from target/firewall)
                    return port, {'status': 'REJECTED (TCP RST)', 'response_ms': elapsed, 'proto': proto, 'desc': desc}
                else:
                    return port, {'status': 'DROP / FILTERED (Timeout)', 'response_ms': elapsed, 'proto': proto, 'desc': desc}
            except socket.timeout:
                return port, {'status': 'DROP / FILTERED (Timeout)', 'response_ms': 2000, 'proto': proto, 'desc': desc}
            except Exception as e:
                return port, {'status': f'ERROR: {str(e)}', 'response_ms': 0, 'proto': proto, 'desc': desc}

        with ThreadPoolExecutor(max_workers=10) as executor:
            futures = [executor.submit(_test_port, p, info) for p, info in EGRESS_PORTS.items()]
            for fut in as_completed(futures):
                p, res = fut.result()
                egress_data['results'][p] = res

        # Analyze critical egress leakages
        open_critical = [p for p in [445, 25, 3389] if egress_data['results'].get(p, {}).get('status') == 'OPEN']
        if open_critical:
            self.add_finding(
                title=f"High-Risk Egress Ports Allowed: {open_critical}",
                severity="HIGH",
                detail=f"Network allows unrestricted outbound traffic on sensitive ports: {open_critical}.",
                evidence=str({p: egress_data['results'][p] for p in open_critical}),
                recommendation="Implement strict egress filtering at the perimeter firewall, permitting only ports 80/443."
            )

        return egress_data

    # =========================================================================
    # 4. WAF & IDS/IPS Fingerprint Engine (Hybrid Passive + Benign Probe)
    # =========================================================================
    def _audit_waf_and_ids(self, active: bool = True) -> dict:
        waf_data = {
            'waf_detected': False,
            'waf_vendor': None,
            'detection_method': None,
            'active_blocking_verified': False,
            'ips_rate_limiting': False
        }

        # 4.1 Passive Header / Cookie Scan
        try:
            resp = self.get(self.get_base_url(), timeout=min(self.timeout, 5))
            if resp is not None:
                headers_lower = {k.lower(): v.lower() for k, v in resp.headers.items()}
                body_lower = (resp.text or "")[:4096].lower()

                for vendor, sigs in WAF_SIGNATURES.items():
                    # Check headers
                    for h in sigs['headers']:
                        if h.lower() in headers_lower:
                            waf_data['waf_detected'] = True
                            waf_data['waf_vendor'] = vendor
                            waf_data['detection_method'] = f"Passive HTTP header match: '{h}'"
                            break

                    # Check body
                    if not waf_data['waf_detected']:
                        for b in sigs['body']:
                            if b.lower() in body_lower:
                                waf_data['waf_detected'] = True
                                waf_data['waf_vendor'] = vendor
                                waf_data['detection_method'] = f"Passive body pattern match: '{b}'"
                                break

                    if waf_data['waf_detected']:
                        break
        except Exception:
            pass

        # 4.2 Active Benign Diagnostic Probe (Controlled non-destructive test)
        if active and resp is not None:
            base_url = self.get_base_url()
            # Benign diagnostic probes specifically structured to test L7 inspection rules
            probe_urls = [
                f"{base_url}/?dystroyer_probe=%27+OR+%271%27=%271",
                f"{base_url}/?dystroyer_diag=%3Cscript%3Ealert(1)%3C/script%3E"
            ]

            for test_url in probe_urls:
                try:
                    probe_resp = self.get(test_url, timeout=min(self.timeout, 5))
                    if probe_resp is not None:
                        # WAFs typically return 403 Forbidden, 406 Not Acceptable, 429, or 501
                        if probe_resp.status_code in [403, 406, 429]:
                            waf_data['waf_detected'] = True
                            waf_data['active_blocking_verified'] = True
                            
                            # Inspect block page content for signatures
                            probe_body = (probe_resp.text or "")[:4096].lower()
                            for vendor, sigs in WAF_SIGNATURES.items():
                                for b in sigs['body']:
                                    if b.lower() in probe_body:
                                        waf_data['waf_vendor'] = vendor
                                        break
                                if waf_data['waf_vendor']:
                                    break

                            self.add_finding(
                                title=f"Active WAF / Perimeter Inspection Triggered ({waf_data['waf_vendor'] or 'Generic WAF'})",
                                severity="INFO",
                                detail=f"Controlled test probe triggered HTTP {probe_resp.status_code} block page.",
                                evidence=f"URL: {test_url} -> Response Code: {probe_resp.status_code}",
                                recommendation="Perimeter application firewall is actively filtering known attack patterns."
                            )
                            break
                except Exception:
                    pass

        if waf_data['waf_detected'] and not waf_data['active_blocking_verified']:
            self.add_finding(
                title=f"WAF / Cloud Proxy Detected ({waf_data['waf_vendor'] or 'Generic'})",
                severity="INFO",
                detail=f"Identified {waf_data['waf_vendor']} via passive signatures.",
                evidence=waf_data.get('detection_method', 'Header signature'),
                recommendation="Ensure WAF rules are properly maintained and tuned to avoid false positives."
            )

        return waf_data


